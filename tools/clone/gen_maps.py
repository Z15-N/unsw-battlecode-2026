"""Embed every known map's static layout (kelp and portals) into known_maps.hpp.

    python tools/clone/gen_maps.py
"""

from __future__ import annotations

import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools"))

from lab.common import KELP, PORTAL, GameMap  # noqa: E402

OUT = pathlib.Path(__file__).resolve().parent / "bot" / "known_maps.hpp"


def code(edge) -> str:
    return "w" if edge.kind == KELP else "p" if edge.kind == PORTAL else "."


def main() -> None:
    seen: dict[str, str] = {}
    maps = []
    for path in sorted((ROOT / "maps").rglob("*.map")):
        text = path.read_text()
        m = GameMap.parse(text)
        key = hashlib.sha1("".join(code(e) for row in m.hedge + m.vedge for e in row).encode()
                           + f"{m.width}x{m.height}{sorted(m.portals.items())}".encode()).hexdigest()
        if key in seen:
            continue
        seen[key] = path.stem
        maps.append((path.stem.lower(), m))
    lines = ["// Generated by tools/clone/gen_maps.py -- do not edit.", "#pragma once", "",
             "namespace known {", "",
             "struct Portal { char orient; int x, y, id; };",
             "struct MapInfo { const char* name; int w, h; const char* hedge; const char* vedge;",
             "                 const Portal* portals; int portal_count; };", ""]
    for i, (name, m) in enumerate(maps):
        hedge = "".join(code(e) for row in m.hedge for e in row)
        vedge = "".join(code(e) for row in m.vedge for e in row)
        ports = [(o, x, y, pid) for pid, ends in sorted(m.portals.items()) for (o, x, y) in ends]
        lines.append(f"inline constexpr Portal portals_{i}[] = {{" +
                     (", ".join(f"{{'{o}',{x},{y},{pid}}}" for o, x, y, pid in ports) or "{'h',0,0,-1}") + "};")
        lines.append(f'inline constexpr const char hedge_{i}[] = "{hedge}";')
        lines.append(f'inline constexpr const char vedge_{i}[] = "{vedge}";')
    lines.append("")
    lines.append("inline constexpr MapInfo maps[] = {")
    for i, (name, m) in enumerate(maps):
        n = sum(len(v) for v in m.portals.values())
        lines.append(f'    {{"{name}", {m.width}, {m.height}, hedge_{i}, vedge_{i}, portals_{i}, {n}}},')
    lines.append("};")
    lines.append(f"inline constexpr int map_count = {len(maps)};")
    lines.append("")
    lines.append("} // namespace known")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} with {len(maps)} maps: {', '.join(n for n, _ in maps)}")


if __name__ == "__main__":
    main()
