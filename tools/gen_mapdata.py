"""Write bot/mapdata.hpp: every known map's static layout for our bot.

    python tools/gen_mapdata.py

Per map: edges (kelp/portal), portal ends, symmetry, starting dragons, and a
per-tile pearl class ('.' never spawns, 'a'.. faster to 'z' slower).
"""

from __future__ import annotations

import hashlib
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from lab.common import KELP, PORTAL, GameMap  # noqa: E402

OUT = ROOT / "bot" / "mapdata.hpp"


def code(edge) -> str:
    return "w" if edge.kind == KELP else "p" if edge.kind == PORTAL else "."


def pearl_class(gap) -> str:
    lo, hi = gap
    if hi == 0:
        return "."
    avg = (lo + hi) / 2
    k = 0
    while avg > 4 and k < 25:     # 'a' <= 4 rounds, each letter ~ x1.5
        avg /= 1.5
        k += 1
    return chr(ord("a") + k)


def main() -> None:
    seen = set()
    maps = []
    for path in sorted((ROOT / "maps").rglob("*.map")):
        m = GameMap.parse(path.read_text())
        key = hashlib.sha1(path.read_bytes().replace(b"\r\n", b"\n").strip()).hexdigest()
        layout = "".join(code(e) for row in m.hedge + m.vedge for e in row) + f"{m.width}x{m.height}"
        if key in seen or layout in seen:
            continue
        seen.update((key, layout))
        maps.append((path.stem.lower(), m))
    out = ["// Generated by tools/gen_mapdata.py -- do not edit.", "#pragma once", "", "namespace mapdata {", "",
           "struct Portal { char orient; int x, y, id; };",
           "struct Spawn { char team; int length, x, y; };",
           "struct Map {",
           "    const char* name; int w, h; char symmetry;   // 'x', 'y', 'r' (both, i.e. rotation) or '?'",
           "    const char* hedge; const char* vedge; const char* pearls;",
           "    const Portal* portals; int portal_count; const Spawn* spawns; int spawn_count;",
           "};", ""]
    for i, (name, m) in enumerate(maps):
        hedge = "".join(code(e) for row in m.hedge for e in row)
        vedge = "".join(code(e) for row in m.vedge for e in row)
        pearls = "".join(pearl_class(m.gaps.get((x, y), (0, 0))) for y in range(m.height) for x in range(m.width))
        ports = [(o, x, y, pid) for pid, ends in sorted(m.portals.items()) for (o, x, y) in ends]
        out.append(f"inline constexpr Portal portals_{i}[] = {{"
                   + (", ".join(f"{{'{o}',{x},{y},{pid}}}" for o, x, y, pid in ports) or "{'h',0,0,-1}") + "};")
        out.append(f"inline constexpr Spawn spawns_{i}[] = {{"
                   + ", ".join(f"{{'{t}',{len(c)},{c[0][0]},{c[0][1]}}}" for t, c in m.dragons) + "};")
        out.append(f'inline constexpr const char hedge_{i}[] = "{hedge}";')
        out.append(f'inline constexpr const char vedge_{i}[] = "{vedge}";')
        out.append(f'inline constexpr const char pearls_{i}[] = "{pearls}";')
    out += ["", "inline constexpr Map maps[] = {"]
    for i, (name, m) in enumerate(maps):
        sym = {"x": "x", "y": "y", "xy": "r"}.get(m.symmetry, "?")
        n_ports = sum(len(v) for v in m.portals.values())
        out.append(f'    {{"{name}", {m.width}, {m.height}, \'{sym}\', hedge_{i}, vedge_{i}, pearls_{i}, '
                   f"portals_{i}, {n_ports}, spawns_{i}, {len(m.dragons)}}},")
    out += ["};", f"inline constexpr int count = {len(maps)};", "", "} // namespace mapdata", ""]
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT}: {len(maps)} maps ({', '.join(n for n, _ in maps)})")


if __name__ == "__main__":
    main()
